package chunkers

import (
	"bytes"
	"io"
	"testing"

	"github.com/stretchr/testify/require"
)

// If min is exactly at the CDC border, it should be returned.
func TestFastCDCBoundaryAtMinSize(t *testing.T) {

	prefix := make([]byte, 64)
	someMatchingBytes := []byte{
		0xC7, 0x75, 0x39, 0xC5, 0xDD, 0x24, 0x82, 0xED, 0x56, 0xEA, 0x0D, 0x6D, 0xAE, 0x40, 0x6C, 0x08,
		0x30, 0xA6, 0xAB, 0xDB, 0x49, 0x9F, 0x97, 0x90, 0x79, 0x2E, 0xEE, 0x21, 0x9A, 0xF6, 0xF1, 0xEC,
		0x1D, 0x21, 0xB6, 0xB1, 0x36, 0x8C, 0x5E, 0xB3, 0x40, 0x33, 0x5C, 0xAE, 0xDF, 0x24, 0xEC, 0x81,
		0xC2, 0x18, 0x6A, 0xBD, 0xE6, 0xE5, 0xB9, 0x56, 0x30, 0xE0, 0x25, 0x74, 0xCF, 0x3D, 0x99, 0x48,
	}
	postfix := make([]byte, 64)

	r := io.MultiReader(bytes.NewReader(prefix), bytes.NewReader(someMatchingBytes), bytes.NewReader(postfix))
	minSize := uint64(len(prefix) + len(someMatchingBytes))
	chunker, err := NewFastCDCChunker(r, ChunkerParams{minSize, minSize * 4, minSize * 16, ""})
	require.NoError(t, err)

	_, chunk, err := chunker.Next()
	require.NoError(t, err)
	require.Len(t, chunk, int(minSize), "a boundary at the min chunk size must produce a chunk of exactly min bytes")

}
